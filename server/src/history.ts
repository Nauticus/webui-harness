import crypto from 'node:crypto';
import fs from 'node:fs';
import fsp from 'node:fs/promises';
import path from 'node:path';
import { DATA_DIR, HISTORY_DIR, KEY_FILE } from './paths';

/**
 * Session history on disk, encrypted at rest.
 *
 * Layout:  <dataDir>/history/<projectId>/<sessionId>.jsonl
 *         one line per message, append-only:
 *         {"seq":3,"role":"tool","c":"v1.<iv_b64>.<ct_b64>","m":"v1.<iv_b64>.<ct_b64>"}
 *
 * `c` (content) and `m` (meta, when present) are AES-256-GCM ciphertext, each
 * with a random 96-bit nonce; `seq`/`role` stay plaintext so the file is
 * still listable. A wrong key fails GCM auth (decryption throws).
 *
 * Key resolution:
 *   1. WEBLISAN_KEY env var (64 hex chars)
 *   2. <dataDir>/key file (64 hex chars, mode 600)
 *   3. neither -> generate, save to <dataDir>/key, and append WEBLISAN_KEY=
 *      to the repo .env (when present) so explicit env wins from next run on.
 */

const ENC_PREFIX = 'v1.';
const IV_LEN = 12;
const TAG_LEN = 16;

export interface HistoryRecord {
  seq: number;
  role: 'user' | 'assistant' | 'tool';
  content: string;
  meta?: Record<string, unknown>;
}

let keyCache: Buffer | null = null;

/** Resolve (or generate on first run) the 32-byte history encryption key. */
export function resolveKey(): Buffer {
  if (keyCache) return keyCache;
  fs.mkdirSync(HISTORY_DIR, { recursive: true });

  const envKey = process.env.WEBLISAN_KEY?.trim();
  if (envKey) {
    if (!/^[0-9a-fA-F]{64}$/.test(envKey)) {
      throw new Error(`WEBLISAN_KEY must be 64 hex chars (32 bytes); got ${envKey.length} chars`);
    }
    keyCache = Buffer.from(envKey, 'hex');
    return keyCache;
  }
  if (fs.existsSync(KEY_FILE)) {
    const raw = fs.readFileSync(KEY_FILE, 'utf8').trim();
    if (!/^[0-9a-fA-F]{64}$/.test(raw)) {
      throw new Error(
        `${KEY_FILE} does not contain a 64-hex key — fix it or set WEBLISAN_KEY explicitly`
      );
    }
    keyCache = Buffer.from(raw, 'hex');
    return keyCache;
  }
  // First run: generate a key.
  const keyHex = crypto.randomBytes(32).toString('hex');
  fs.writeFileSync(KEY_FILE, keyHex + '\n', { mode: 0o600 });
  const envFile = path.join(DATA_DIR, '..', '.env');
  if (fs.existsSync(envFile)) {
    fs.appendFileSync(envFile, `\n# History encryption key (auto-generated by weblisan on first run)\nWEBLISAN_KEY=${keyHex}\n`);
  }
  keyCache = Buffer.from(keyHex, 'hex');
  console.warn(`[weblisan] generated history encryption key -> ${KEY_FILE}`);
  return keyCache;
}

function enc(key: Buffer, plaintext: string): string {
  const iv = crypto.randomBytes(IV_LEN);
  const cipher = crypto.createCipheriv('aes-256-gcm', key, iv);
  const ct = Buffer.concat([cipher.update(plaintext, 'utf8'), cipher.final()]);
  return `${ENC_PREFIX}${iv.toString('base64')}.${Buffer.concat([ct, cipher.getAuthTag()]).toString('base64')}`;
}

function dec(key: Buffer, blob: string): string {
  if (!blob.startsWith(ENC_PREFIX)) {
    throw new Error('history record is not v1-encrypted — wrong WEBLISAN_KEY or corrupted file');
  }
  const parts = blob.slice(ENC_PREFIX.length).split('.');
  const iv = Buffer.from(parts[0]!, 'base64');
  const data = Buffer.from(parts[1]!, 'base64');
  const tag = data.subarray(data.length - TAG_LEN);
  const ct = data.subarray(0, data.length - TAG_LEN);
  const decipher = crypto.createDecipheriv('aes-256-gcm', key, iv);
  decipher.setAuthTag(tag);
  try {
    return Buffer.concat([decipher.update(ct), decipher.final()]).toString('utf8');
  } catch {
    throw new Error('cannot decrypt history (GCM auth failed) — wrong WEBLISAN_KEY?');
  }
}

function projectDir(projectId: string): string {
  return path.join(HISTORY_DIR, projectId);
}

function sessionFile(sessionId: string, projectId: string): string {
  return path.join(projectDir(projectId), `${sessionId}.jsonl`);
}

function encodeLine(key: Buffer, seq: number, role: HistoryRecord['role'], content: string, meta?: Record<string, unknown>): string {
  return JSON.stringify({
    seq,
    role,
    c: enc(key, content),
    ...(meta ? { m: enc(key, JSON.stringify(meta)) } : {}),
  });
}

async function countLines(file: string): Promise<number> {
  try {
    const raw = await fsp.readFile(file, 'utf8');
    return raw.length === 0 ? 0 : raw.trimEnd().split('\n').length;
  } catch {
    return 0;
  }
}

/** Append one message; returns its seq. */
export async function appendRecord(
  sessionId: string,
  projectId: string,
  rec: { role: HistoryRecord['role']; content: string; meta?: Record<string, unknown> }
): Promise<number> {
  const key = resolveKey();
  const file = sessionFile(sessionId, projectId);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const seq = (await countLines(file)) + 1;
  await fsp.appendFile(file, encodeLine(key, seq, rec.role, rec.content, rec.meta) + '\n');
  return seq;
}

/** Write a whole session file (used by the one-time DB migration). */
export async function writeHistory(
  sessionId: string,
  projectId: string,
  records: { role: HistoryRecord['role']; content: string; meta?: Record<string, unknown> }[]
): Promise<void> {
  const key = resolveKey();
  const file = sessionFile(sessionId, projectId);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const lines = records.map((r, i) => encodeLine(key, i + 1, r.role, r.content, r.meta)).join('\n');
  await fsp.writeFile(file, lines + '\n');
}

/** Read + decrypt a session's history (empty when the file is absent). */
export async function readHistory(sessionId: string, projectId: string): Promise<HistoryRecord[]> {
  const key = resolveKey();
  let raw: string;
  try {
    raw = await fsp.readFile(sessionFile(sessionId, projectId), 'utf8');
  } catch {
    return [];
  }
  const out: HistoryRecord[] = [];
  for (const line of raw.split('\n')) {
    if (!line.trim()) continue;
    const r = JSON.parse(line) as { seq: number; role: string; c: string; m?: string };
    let meta: Record<string, unknown> | undefined;
    if (r.m) {
      try {
        meta = JSON.parse(dec(key, r.m)) as Record<string, unknown>;
      } catch {
        meta = undefined; // meta loss is non-fatal
      }
    }
    out.push({ seq: r.seq, role: r.role as HistoryRecord['role'], content: dec(key, r.c), meta });
  }
  return out.sort((a, b) => a.seq - b.seq);
}

export async function deleteSessionHistory(sessionId: string, projectId: string): Promise<void> {
  try {
    await fsp.unlink(sessionFile(sessionId, projectId));
  } catch {
    /* already gone */
  }
}

export async function deleteProjectHistory(projectId: string): Promise<void> {
  try {
    await fsp.rm(projectDir(projectId), { recursive: true, force: true });
  } catch {
    /* already gone */
  }
}
